def test_build_digest_markdown_counts_only_overdue_eol_assets(digest_session):
    now = datetime(2026, 7, 7, tzinfo=timezone.utc)
    with Session(digest_session) as s:
        rid = _mk_resource(s)
        s.add(
            EolRegistry(resource_id=rid, asset_name="past-eol", eol_date=now - timedelta(days=30))
        )
        s.add(
            EolRegistry(resource_id=rid, asset_name="future-eol", eol_date=now + timedelta(days=30))
        )
        s.add(EolRegistry(resource_id=rid, asset_name="no-eol-date", eol_date=None))
        s.commit()

    md = build_digest_markdown(now=now)
    assert "| EOL assets overdue | 1 |" in md


def test_build_digest_markdown_handles_naive_eol_dates(digest_session):
    """EolRegistry rows written before tz-awareness was enforced everywhere
    could carry a naive datetime — must not raise a tz-comparison TypeError."""
    now = datetime(2026, 7, 7, tzinfo=timezone.utc)
    with Session(digest_session) as s:
        rid = _mk_resource(s)
        s.add(
            EolRegistry(
                resource_id=rid,
                asset_name="naive-past-eol",
                eol_date=datetime(2020, 1, 1),  # naive, no tzinfo
            )
        )
        s.commit()

    md = build_digest_markdown(now=now)
    assert "| EOL assets overdue | 1 |" in md


