def test_build_digest_markdown_counts_only_open_drift(digest_session):
    with Session(digest_session) as s:
        rid = _mk_resource(s)
        s.add(DriftEvent(resource_id=rid, drift_type="config_drift", field="x", status="open"))
        s.add(DriftEvent(resource_id=rid, drift_type="config_drift", field="y", status="resolved"))
