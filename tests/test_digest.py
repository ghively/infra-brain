def test_build_digest_markdown_counts_open_and_triage_as_open_vulns(digest_session):
    with Session(digest_session) as s:
        rid = _mk_resource(s)
        s.add(
            VulnQueueItem(resource_id=rid, cve_id="CVE-2021-0001", severity="high", status="open")
        )
        s.add(
            VulnQueueItem(resource_id=rid, cve_id="CVE-2021-0002", severity="low", status="triage")
        )
        s.add(
            VulnQueueItem(
                resource_id=rid, cve_id="CVE-2021-0003", severity="high", status="resolved"
            )
        )
        s.commit()

    md = build_digest_markdown()
    assert "Open vulnerabilities | 2 " in md


def test_build_digest_markdown_counts_critical_subset_of_open_vulns(digest_session):
    with Session(digest_session) as s:
        rid = _mk_resource(s)
        s.add(
            VulnQueueItem(
                resource_id=rid, cve_id="CVE-2021-1001", severity="critical", status="open"
            )
        )
        s.add(
            VulnQueueItem(resource_id=rid, cve_id="CVE-2021-1002", severity="high", status="open")
        )
        # Resolved critical must not count even though severity matches.
        s.add(
            VulnQueueItem(
                resource_id=rid, cve_id="CVE-2021-1003", severity="critical", status="resolved"
            )
        )
        s.commit()

    md = build_digest_markdown()
    assert "critical: 1" in md


