def test_post_digest_returns_markdown_even_when_publish_fails(digest_session):
    from infra_brain import digest as digest_mod

    with (
        patch.object(digest_mod, "logger") as mock_logger,
        patch(
            "infra_brain.tools.confluence.upsert_confluence_page",
            side_effect=RuntimeError("confluence down"),
        ),
    ):
        md = digest_mod.post_digest()

    assert "Infra Brain — Fleet Digest" in md
    mock_logger.warning.assert_called()


def test_post_digest_logs_but_does_not_raise_on_write_gate_denial(digest_session):
    from infra_brain import digest as digest_mod

    with (
        patch.object(digest_mod, "logger") as mock_logger,
        patch(
            "infra_brain.tools.confluence.upsert_confluence_page",
            side_effect=PermissionError("blocked by write gate"),
        ),
    ):
        md = digest_mod.post_digest()

    assert "Infra Brain — Fleet Digest" in md
    mock_logger.warning.assert_called()
    assert "BLOCKED" in mock_logger.warning.call_args[0][0]
