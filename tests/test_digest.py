"""Module tests for infra_brain.digest (MR-E TEST-4).

build_digest_markdown() had zero direct test coverage — only touched
transitively (test_scripts_store.py, test_mcp_server.py, test_vendored_assets.py
reference "digest" for unrelated reasons). Uses a real in-memory SQLite
session (not a mock) so the actual COUNT/filter semantics are proven, not
just that certain methods were called.
"""

from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from unittest.mock import patch

import pytest
from sqlalchemy.orm import Session

from infra_brain.db.models import (
    ComplianceViolation,
    DriftEvent,
    EolRegistry,
    Resource,
    VulnQueueItem,
)
from infra_brain.digest import build_digest_markdown

from tests.support.pg import make_engine


@pytest.fixture
def engine():
    eng = make_engine()
    return eng


@pytest.fixture
def digest_session(engine):
    @contextmanager
    def _get_session():
        with Session(engine) as s:
            yield s

    with patch("infra_brain.digest.get_session", _get_session):
        yield engine


def _mk_resource(session, name="host-01"):
    r = Resource(
        domain="test",
        type="host",
        name=name,
        source="test",
        zone="corpor",
        last_seen=datetime.now(timezone.utc),
    )
    session.add(r)
    session.flush()
    return r.id


