def test_route_parity():
    """The app must expose exactly the routes in EXPECTED_ROUTES — no more, no less."""
    app = create_app()
    collected = _collect_routes(app.router)

    # Tripwire: if the collection helper breaks (e.g. FastAPI changes its internal
    # wrapper shape), it might silently return a partial set.  A shrunken
    # EXPECTED_ROUTES would then pass while hiding real route losses.  This floor
    # catches that failure mode and turns it into a loud error.
    assert len(collected) >= 70, (
        f"_collect_routes returned only {len(collected)} routes — expected at least 70. "
        "This likely means the collection helper is broken (FastAPI internal structure "
        "changed), not that routes were intentionally removed."
    )

    actual = set(collected)

    missing = EXPECTED_ROUTES - actual
    extra = actual - EXPECTED_ROUTES

    assert not missing, (
        f"Routes present in EXPECTED_ROUTES but MISSING from the app "
        f"({len(missing)}):\n" + "\n".join(f"  {m} {p}" for m, p in sorted(missing))
    )
    assert not extra, (
        f"Routes present in the app but NOT in EXPECTED_ROUTES "
        f"({len(extra)}):\n" + "\n".join(f"  {m} {p}" for m, p in sorted(extra))
    )


def test_no_duplicate_routes():
    """No (method, path) pair should be mounted more than once."""
    app = create_app()
    routes = _collect_routes(app.router)

    counts = Counter(routes)
    duplicates = {k: v for k, v in counts.items() if v > 1}

    assert not duplicates, (
        f"Duplicate route mounts detected ({len(duplicates)} pairs):\n"
        + "\n".join(f"  {m} {p} x{n}" for (m, p), n in sorted(duplicates.items()))
    )
