"""Route-parity guard (Phase 3 Task 12).

Builds the full app via create_app() and asserts that the complete set of
(method, path) tuples matches the frozen expected set below.  Any future
change that adds, drops, or renames a route will fail this test.

A second assertion verifies that no (method, path) pair is mounted twice
(no duplicate route registrations).

How routes are collected:
    FastAPI stores included routers as _IncludedRouter wrapper objects (not
    directly as APIRoute entries) on app.router.routes.  _collect_routes()
    uses isinstance() against the public fastapi.routing.APIRoute class to
    identify real route entries, and recurses into wrapper objects by:
      1. Trying r.include_context.included_router (the documented internal path)
      2. Falling back to r.original_router (alias to the same object in current
         FastAPI versions, kept as belt-and-suspenders)
      3. Falling back to r.routes for any other container-like object (e.g. Mount)
    A cycle guard (set of id()s) prevents infinite recursion.  The result is
    all 76 (method, path) pairs the running app serves.
"""

from __future__ import annotations

from collections import Counter

from fastapi.routing import APIRoute

from infra_brain.main import create_app

# ---------------------------------------------------------------------------
# Route collector
# ---------------------------------------------------------------------------


def _collect_routes(router, _seen: set[int] | None = None) -> list[tuple[str, str]]:
    """Recursively collect (METHOD, path) from a router or route-container object.

    Uses isinstance(r, APIRoute) — the public FastAPI class — rather than
    string-matching type names, so the check is version-stable.  Recurses into
    _IncludedRouter wrappers via include_context.included_router (preferred)
    with original_router as a fallback, then .routes for any other container.
    A cycle guard prevents re-visiting the same router object.
    """
    if _seen is None:
        _seen = set()

    router_id = id(router)
    if router_id in _seen:
        return []
    _seen.add(router_id)

    result: list[tuple[str, str]] = []
    for r in router.routes:
        if isinstance(r, APIRoute):
            for method in sorted(r.methods):
                result.append((method, r.path))
        else:
            # Prefer the proven include_context path (FastAPI internal structure).
            ic = getattr(r, "include_context", None)
            if ic is not None:
                sub_router = getattr(ic, "included_router", None)
                if sub_router is not None and id(sub_router) not in _seen:
                    result.extend(_collect_routes(sub_router, _seen))
                    continue

            # Belt-and-suspenders: try original_router (same object in current
            # FastAPI versions; kept in case include_context shape shifts).
            orig = getattr(r, "original_router", None)
            if orig is not None and id(orig) not in _seen:
                result.extend(_collect_routes(orig, _seen))
                continue

            # Last resort: walk any .routes container directly (e.g. Mount).
            sub_routes = getattr(r, "routes", None)
            if sub_routes is not None:
                for sr in sub_routes:
                    if isinstance(sr, APIRoute):
                        for method in sorted(sr.methods):
                            result.append((method, sr.path))

    return result


